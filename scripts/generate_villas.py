STATUS_CLASS = {
    "Pass": "pass", "Closed": "pass",
    "Pending": "pend", "Open": "pend", "Review": "pend",
    "Not Recorded": "nr", "N/A": "nr",
    "Fail": "fail",
    "Waiting": "wait",
}
PRI_CLASS = {"High": "pri-high", "Medium": "pri-med", "Low": "pri-low"}

def badge(status):
    cls = STATUS_CLASS.get(status, "nr")
    return f'<span class="badge b-{cls}" data-search="{esc(status)}">{esc(status)}</span>'

def search_blob(*parts):
    return esc(" ".join(str(p) for p in parts if p))

def render_checklist(rows):
    out = []
    last_phase = None
    for item, status, evidence, date, issue in rows:
        phase = item.split(' — ')[0] if ' — ' in item else item.split(' - ')[0]
        if phase != last_phase:
            out.append(f'<tr class="phase-row"><td colspan="3" data-search="{esc(phase)}"><span class="phase-tag">{esc(phase)}</span></td></tr>')
            last_phase = phase
        label = item.split(' — ',1)[1] if ' — ' in item else (item.split(' - ',1)[1] if ' - ' in item else item)
        issue_html = ""
        if issue:
            chips = "".join(f'<a class="chip" href="#iss-{esc(i.strip())}">{esc(i.strip())}</a>' for i in str(issue).split("/"))
            issue_html = f'<div class="issue-chips">{chips}</div>'
        evidence_html = f'<div class="cell-note">{esc(evidence)}</div>' if evidence else ""
        blob = search_blob(phase, label, status, evidence, issue)
        out.append(f'''<tr data-search="{blob}">
          <td class="col-item">{esc(label)}{evidence_html}{issue_html}</td>
          <td class="col-status">{badge(status)}</td>
          <td class="col-date mono">{esc(date)}</td>
        </tr>''')
    return "\n".join(out)

def render_devrows(rows):
    out = []
    for dev, loc, model, serial, act, test, find in rows:
        flagged = ' class="row-flag"' if find else ""
        note = f'<div class="cell-note">{esc(find)}</div>' if find else ""
        blob = search_blob(dev, loc, model, serial, find)
        out.append(f'''<tr{flagged} data-search="{blob}">
          <td class="mono col-id">{esc(dev)}</td>
          <td>{esc(loc)}{note}</td>
          <td class="mono muted">{esc(model)}</td>
          <td class="mono">{esc(serial)}</td>
          <td class="col-status">{badge(act)}</td>
          <td class="col-status">{badge(test)}</td>
        </tr>''')
    return "\n".join(out)

def render_closeout(rows):
    out = []
    for item, status, evidence, date in rows:
        note = f'<div class="cell-note">{esc(evidence)}</div>' if evidence else ""
        blob = search_blob(item, status, evidence)
        out.append(f'''<tr data-search="{blob}">
          <td class="col-item">{esc(item)}{note}</td>
          <td class="col-status">{badge(status)}</td>
          <td class="col-date mono">{esc(date)}</td>
        </tr>''')
    return "\n".join(out)

def render_modules_out(rows):
    out = []
    last_key = None
    for panel, module, model, outp, load, wmatch, ftest, notes in rows:
        key = (panel, module)
        if key != last_key:
            out.append(f'<tr class="module-row"><td colspan="5" data-search="{esc(panel)} {esc(module)} {esc(model)}"><span class="phase-tag">{esc(panel)} &middot; {esc(module)}</span><span class="model-tag mono">{esc(model)}</span></td></tr>')
            last_key = key
        row_cls = ""
        if ftest == "Fail":
            row_cls = ' class="row-fail"'
        elif str(load).startswith("UNASSIGNED"):
            row_cls = ' class="row-muted"'
        blob = search_blob(panel, module, outp, load, notes)
        out.append(f'''<tr{row_cls} data-search="{blob}">
          <td class="mono col-out">{esc(outp)}</td>
          <td>{esc(load)}<div class="cell-note">{esc(notes)}</div></td>
          <td class="col-status">{badge(wmatch)}</td>
          <td class="col-status">{badge(ftest)}</td>
        </tr>''')
    return "\n".join(out)

def render_modreg(rows):
    out = []
    for panel, module, model, serial, act, test in rows:
        blob = search_blob(panel, module, serial)
        out.append(f'''<tr data-search="{blob}">
          <td>{esc(panel)}</td>
          <td class="mono col-id">{esc(module)}</td>
          <td class="mono muted">{esc(model)}</td>
          <td class="mono">{esc(serial)}</td>
          <td class="col-status">{badge(act)}</td>
          <td class="col-status">{badge(test)}</td>
        </tr>''')
    return "\n".join(out)

def render_issues(rows, villa_num):
    cards = []
    for iid, villa, area, typ, desc, pri, status, owner, opened, closed, res, tmpl in rows:
        blob = search_blob(iid, area, typ, desc, status, res)
        pricls = PRI_CLASS.get(pri, "pri-low")
        dates = f"Opened {esc(opened)}" + (f" &middot; Closed {esc(closed)}" if closed else "")
        cards.append(f'''<article class="issue-card" id="iss-{esc(iid)}" data-search="{blob}">
          <header class="issue-head">
            <span class="mono issue-id">{esc(iid)}</span>
            <span class="pri-dot {pricls}" title="{esc(pri)} priority"></span>
            <span class="issue-area">{esc(area)}</span>
            {badge(status)}
          </header>
          <p class="issue-type">{esc(typ)}</p>
          <p class="issue-desc">{esc(desc)}</p>
          <p class="issue-res"><span class="label-sm">Resolution</span> {esc(res)}</p>
          <p class="issue-meta mono">{esc(owner)} &middot; {dates}</p>
        </article>''')
    return "\n".join(cards)

def render_notes(notes_text):
    lines = [l.strip() for l in notes_text.split('\n') if l.strip()]
    if lines and lines[0].upper().startswith('COMMISSIONING NOTES'):
        lines = lines[1:]
    items = []
    for i, n in enumerate(lines, 1):
        items.append(f'<li><span class="note-mark mono">{i:02d}</span><span>{esc(n)}</span></li>')
    return "\n".join(items), len(lines)

